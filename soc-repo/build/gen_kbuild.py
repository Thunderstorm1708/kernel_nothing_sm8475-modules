#!/usr/bin/env python3
# SPDX-License-Identifier: GPL-2.0
"""Translate the soc-repo module registry (modules.bzl, DDK) into a Kbuild file.

The Bazel registry is what decides which soc-repo modules a target builds and
from which sources; the per-directory Makefiles of this tree do not always
follow it (modules only registered in modules.bzl, objects that differ). For a
LineageOS inline (make) build, this writes build/Kbuild.<target_variant>: every
module the registry enables for that target, with its sources, conditional
sources, includes and copts, as kbuild composite objects relative to the soc
staging dir (common sources + this repo, see common_sources.mk).

Development tool; the output is committed and the ROM build only runs make:

  gen_kbuild.py --starlark <starlark_check.py> --layout <layout.json> \
      --config <kernel .config> [--tv waipio_perf]
"""
import argparse
import importlib.util
import os
import re
import sys

ap = argparse.ArgumentParser()
ap.add_argument("--starlark", required=True)
ap.add_argument("--layout", required=True)
ap.add_argument("--config", required=True)
ap.add_argument("--tv", default="waipio_perf")
args = ap.parse_args()

HERE = os.path.dirname(os.path.abspath(__file__))
SOC = os.path.dirname(HERE)

sys.setrecursionlimit(10000)
sys.argv = ["starlark_check.py", args.layout]
spec = importlib.util.spec_from_file_location("starlark", args.starlark)
h = importlib.util.module_from_spec(spec)
spec.loader.exec_module(h)
h.eval_package("soc-repo")
REG = h.PACKAGES["soc-repo"]

KCONFIG = {}
for line in open(args.config):
    m = re.match(r"(CONFIG_\w+)=(.*)", line)
    if m:
        KCONFIG[m.group(1)] = m.group(2)

prefix = args.tv + "/"
mods = {k: v["kw"] for k, v in REG.items() if k.startswith(prefix) and v["rule"] == "ddk_module"}


def enabled(opt):
    return KCONFIG.get(opt, "n") in ("y", "m")


def includes_closure(name, seen=None):
    seen = seen if seen is not None else set()
    if name in seen or name not in mods:
        return []
    seen.add(name)
    kw = mods[name]
    out = list(kw.get("includes") or [])
    for d in kw.get("deps") or []:
        if d.startswith(":" + prefix):
            out += includes_closure(d[1:], seen)
    return out


owner = {}
lines = [
    "# SPDX-License-Identifier: GPL-2.0",
    f"# Generated by build/gen_kbuild.py from modules.bzl ({args.tv}). Do not edit.",
    "# Paths are relative to the soc staging dir, which is the kbuild M.",
    "",
]
wrappers = {}
GEN = {}
for name in sorted(mods):
    kw = mods[name]
    out = kw["out"]
    mod = out[:-3]
    srcs = [s for s in kw.get("srcs") or []]
    for opt, br in (kw.get("conditional_srcs") or {}).items():
        srcs += br.get(enabled(opt), [])
    cfiles = [s for s in srcs if s.endswith((".c", ".S"))]
    for s in srcs:
        rec = REG.get(s)
        if rec is None or rec["rule"] not in ("genrule", "hermetic_genrule"):
            continue
        outs = [o for o in rec["kw"].get("outs") or [] if o.endswith(".c")]
        if s == "net/wireless/shipped-certs" and outs and not rec["kw"].get("srcs"):
            # The Bazel rule cats no certificate (its srcs are empty), so the
            # built cfg80211 carries an empty shipped_regdb_certs: do the same
            w = f"build/kbuild-objs/{mod}__shipped-certs.c"
            GEN[w] = ('#include "../../net/wireless/reg.h"\n'
                            "const u8 shipped_regdb_certs[] = {\n};\n"
                            "unsigned int shipped_regdb_certs_len = sizeof(shipped_regdb_certs);\n")
            cfiles.append(w)
        else:
            sys.exit(f"{name}: unsupported generated source {s}")
    if not cfiles:
        sys.exit(f"{name}: no sources")
    moddir = os.path.dirname(name[len(prefix):])
    modpath = f"{moddir}/{mod}" if moddir else mod
    objs = []
    for s in cfiles:
        o = s[:-2] + ".o"
        if o in owner and owner[o] != modpath:
            w = f"build/kbuild-objs/{re.sub(r'[^A-Za-z0-9_]', '_', mod)}__{os.path.basename(s)}"
            wrappers[w] = s
            o = w[:-2] + ".o"
        owner[o] = modpath
        objs.append(o)
    if modpath + ".o" in objs:
        if objs == [modpath + ".o"]:
            objs = []
        else:
            w = f"build/kbuild-objs/{re.sub(r'[^A-Za-z0-9_]', '_', mod)}__main.c"
            wrappers[w] = modpath + ".c"
            objs[objs.index(modpath + ".o")] = w[:-2] + ".o"
    incs = list(dict.fromkeys(includes_closure(name)))
    flags = [f"-I$(src)/{d}" for d in incs] + list(kw.get("copts") or [])
    lines.append(f"# {name}")
    lines.append(f"obj-m += {modpath}.o")
    if objs:
        lines.append(f"{modpath}-y := " + " ".join(objs))
    for o in objs or [modpath + ".o"]:
        if flags:
            lines.append(f"CFLAGS_{o} += " + " ".join(flags))
    lines.append("")

with open(os.path.join(HERE, "Kbuild." + args.tv), "w") as f:
    f.write("\n".join(lines))
wdir = os.path.join(HERE, "kbuild-objs")
os.makedirs(wdir, exist_ok=True)
for f in os.listdir(wdir):
    os.remove(os.path.join(wdir, f))
for w, s in wrappers.items():
    with open(os.path.join(SOC, w), "w") as f:
        f.write("// SPDX-License-Identifier: GPL-2.0\n"
                "/* Generated by build/gen_kbuild.py: a source shared by two modules,\n"
                " * or one named like its composite module. */\n"
                f'#include "../../{s}"\n')
for w, text in GEN.items():
    with open(os.path.join(SOC, w), "w") as f:
        f.write("// SPDX-License-Identifier: GPL-2.0\n/* Generated by build/gen_kbuild.py */\n" + text)
print(f"{len(mods)} modules, {len(wrappers)} wrapper objects")
